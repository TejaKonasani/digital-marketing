export function getOpportunityById(id, list = initialOpportunities) {
  if (!id) return null
  const clean = String(id).trim().toLowerCase()
  return (
    list.find(
      (o) =>
        o.id.toLowerCase() === clean ||
        o.name.toLowerCase() === clean ||
        o.id.replace('OPP-', '').toLowerCase() === clean.replace('opp-', '')
    ) || list[0]
  )
}
