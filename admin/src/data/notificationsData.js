export function calculateNotificationMetrics(items = initialNotifications) {
  const unreadCount = items.filter((n) => !n.read).length
  const actionRequiredCount = items.filter((n) => n.actionRequired).length
  const failedCommsCount = items.filter(
    (n) => n.categoryKey === 'communications' && n.status.toLowerCase().includes('fail')
  ).length
  const criticalAlertsCount = items.filter(
    (n) => n.priority.toLowerCase() === 'critical' || n.categoryKey === 'system'
  ).length
  const todayCount = items.length

  return {
    unread: unreadCount,
    unreadSubtext: '+4 since yesterday',
    actionRequired: actionRequiredCount,
    actionRequiredSubtext: '3 approvals · 5 tasks',
    failedCommunications: failedCommsCount,
    failedCommunicationsSubtext: '-2 since yesterday',
    criticalAlerts: criticalAlertsCount,
    criticalAlertsSubtext: '1 system · 1 agent',
    today: todayCount,
    todaySubtext: '+6 vs yesterday'
  }
}
