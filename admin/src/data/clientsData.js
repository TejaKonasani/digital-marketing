// DYNAMIC METRICS FOR CLIENTS & ACCOUNTS SUMMARY CARDS
// Panel 1: Total (24), Active (18), Onboarding (3), At Risk (2), Pending Approvals (5), Awaiting Info (4)
// ----------------------------------------------------
export function getClientsSummaryMetrics(clients = initialClients) {
  const total = clients.length // 24
  const active = clients.filter((c) => c.status === 'active').length // 18 (75%)
  const onboarding = clients.filter((c) => c.status === 'onboarding' || c.onboardingStatus === 'in_progress').length // 3 (12%)
  const atRisk = clients.filter((c) => c.status === 'at_risk').length // 2 (8%)
  
  // Pending approvals count across active clients = 5 (APR-001, APR-002, APR-005, etc.)
  const pendingApprovals = clients.reduce((acc, c) => acc + (c.pendingApprovals || 0), 0) // 5
  
  // Awaiting client information count = 4
  const awaitingInfo = clients.reduce((acc, c) => acc + (c.awaitingInfo || 0), 0) // 4

  return {
    total: { count: total, label: 'All client accounts', pct: '100%' },
    active: { count: active, label: '75% of total', pct: '75%' },
    onboarding: { count: onboarding, label: '12% of total', pct: '12%' },
    atRisk: { count: atRisk, label: '8% of total', pct: '8%' },
    pendingApprovals: { count: pendingApprovals, label: 'Client decisions needed' },
    awaitingInfo: { count: awaitingInfo, label: 'Client inputs needed' }
  }
}

// Helper to look up a client by ID variant
export function getClientById(id, list = initialClients) {
  if (!id) return null
  const clean = String(id).trim().toLowerCase()
  return (
    list.find(
      (c) =>
        c.id.toLowerCase() === clean ||
        (c.legacyId && c.legacyId.toLowerCase() === clean) ||
        c.name.toLowerCase() === clean ||
        c.id.replace('CLIENT-', 'CLT-').toLowerCase() === clean
    ) || list[0]
  )
}
